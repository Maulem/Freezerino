# Generates FoodData.kt (categories, dish markers, food list) from the web app's categories.js and foods.js,
# so the Android app classifies foods exactly like the website. Run from the repo root:
#   python android/tools/gen_data.py
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
cat_js = (root / "categories.js").read_text(encoding="utf-8")
foods_js = (root / "foods.js").read_text(encoding="utf-8")

def js_to_json(s):
    s = re.sub(r"//[^\n]*", "", s)
    s = re.sub(r'([{,]\s*)([A-Za-z_]+)\s*:', r'\1"\2":', s)
    s = re.sub(r",(\s*[\]}])", r"\1", s)
    return json.loads(s)

cats_src = cat_js[cat_js.index("export const CATEGORIES = ") + len("export const CATEGORIES = "):]
cats_src = cats_src[:cats_src.index("];") + 1]
cats = js_to_json(cats_src)
dish_src = cat_js[cat_js.index("const DISH = wordsRe(") + len("const DISH = wordsRe("):]
dish = js_to_json(dish_src[:dish_src.index("]);") + 1])
foods_src = foods_js[foods_js.index("export const FOODS = ") + len("export const FOODS = "):]
foods = js_to_json(foods_src[:foods_src.index("];") + 1])

q = lambda s: json.dumps(s, ensure_ascii=False).replace("$", "\\$")
def lst(xs, per=8):
    rows = [", ".join(q(x) for x in xs[i:i + per]) for i in range(0, len(xs), per)]
    return "listOf(\n" + ",\n".join("            " + r for r in rows) + ",\n        )"
def mp(d):
    return "mapOf(" + ", ".join(f"{q(k)} to {v}" for k, v in d.items()) + ")" if d else "emptyMap()"

out = ["// GENERATED by android/tools/gen_data.py from categories.js and foods.js. Do not edit by hand.",
       "package com.nkoindustries.freezerino.data", "",
       "val CATEGORIES: List<Category> = listOf("]
for c in cats:
    out.append(f"    Category(\n        id = {q(c['id'])}, icon = {q(c['icon'])}, label = {q(c['label'])}, months = {c['months']},\n"
               f"        long = {mp(c.get('long', {}))}, short = {mp(c.get('short', {}))},\n        words = {lst(c['words'])},\n    ),")
out.append(")")
out.append("")
out.append("val DISH_WORDS: List<String> = " + lst(dish).replace("\n            ", "\n    ").replace("\n        )", "\n)"))
out.append("")
out.append("val FOODS: List<String> = " + lst(foods).replace("\n            ", "\n    ").replace("\n        )", "\n)"))
dest = root / "android/app/src/main/java/com/nkoindustries/freezerino/data/FoodData.kt"
dest.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(cats)} categories, {len(dish)} dish markers, {len(foods)} foods -> {dest}")
